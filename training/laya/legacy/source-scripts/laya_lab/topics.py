def soe_label(c):
    """国企/央企判定:证据在 companyDescription 的控制人表述里,不在业务文本里。"""
    text = (desc(c) or "") + " | " + hay(c)
    soe = re.search(SOE_PAT, text)
    private = re.search(PRIVATE_PAT, text)
    if not soe and not private:
        return None
    if private and not soe:
        return 0, "资料为自然人/民营控制,非国资"
    if re.search(r"国务院国资委|国务院国有资产|央企", text):
        return 3, "央企/国务院国资委控制表述"
    return 2, "国资/地方国企控制表述"


def _share_band(s):
    return None if s is None else int(round(s * 100))


